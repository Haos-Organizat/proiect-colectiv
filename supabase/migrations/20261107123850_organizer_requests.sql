CREATE TABLE IF NOT EXISTS organizer_requests (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    organization_name VARCHAR(60) NOT NULL,
    message VARCHAR(300),
    status VARCHAR(20) NOT NULL DEFAULT 'in_asteptare'
        CHECK (status IN ('in_asteptare', 'aprobata', 'respinsa')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS organizer_requests_one_pending_per_user
    ON organizer_requests (user_id)
    WHERE status = 'in_asteptare';

CREATE UNIQUE INDEX IF NOT EXISTS organizer_requests_unique_organization_name
    ON organizer_requests (lower(organization_name))
    WHERE status <> 'respinsa';

ALTER TABLE organizer_requests ENABLE ROW LEVEL SECURITY;